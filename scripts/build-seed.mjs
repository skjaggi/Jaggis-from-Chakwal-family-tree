// Builds site/data/seed.json (used by preview mode) and supabase/seed.sql
// (loaded into the database once) from data/family.source.json.
//
//   node scripts/build-seed.mjs
//
// Ids are derived from each person's slug, so re-running gives the same ids.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'data/family.source.json'), 'utf8'));

const uuid = (s) => {
  const h = createHash('sha1').update('jaggi-tree:' + s).digest('hex');
  // Shape it like a version-5 UUID.
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const bySlug = new Map(src.people.map((p) => [p.slug, p]));
const people = [];
const details = [];
const parentChild = [];
const unions = [];

src.people.forEach((p, order) => {
  const id = uuid(p.slug);
  people.push({
    id,
    title: p.title ?? null,
    given_name: p.given,
    surname: p.surname ?? null,
    other_names: p.other_names ?? null,
    gender: p.gender ?? 'unknown',
    generation: p.gen,
    birth_order: order + 1,
    is_living: p.living ?? null,
    photo_path: null,
    photo_visibility: 'public',
  });
  const sources = (p.src || '').split(',').filter(Boolean).map((k) => src.sources[k]).join('\n');
  details.push({
    person_id: id,
    // Generations 1 to 4 are historical records; later generations may be living.
    visibility: p.gen <= 4 ? 'public' : 'branch',
    birth_date: null,
    birth_place: p.birth_place ?? null,
    death_date: null,
    death_place: null,
    profession: null,
    notes: p.notes ?? null,
    sources: sources || null,
    uncertainty: p.uncertainty ?? null,
  });
  for (const par of p.parents || []) {
    if (!bySlug.has(par)) throw new Error(`${p.slug}: unknown parent ${par}`);
    parentChild.push({ id: uuid(`pc:${par}:${p.slug}`), parent_id: uuid(par), child_id: id, kind: 'biological', confidence: 'confirmed', note: null });
  }
  for (const par of p.uncertainParents || []) {
    if (!bySlug.has(par)) throw new Error(`${p.slug}: unknown parent ${par}`);
    parentChild.push({ id: uuid(`pc:${par}:${p.slug}`), parent_id: uuid(par), child_id: id, kind: 'biological', confidence: 'uncertain', note: p.uncertainty ?? null });
  }
  (p.spouses || []).forEach((sp, i) => {
    if (!bySlug.has(sp)) throw new Error(`${p.slug}: unknown spouse ${sp}`);
    unions.push({ id: uuid(`u:${p.slug}:${sp}`), partner_a: id, partner_b: uuid(sp), status: 'married', start_date: null, end_date: null, sort_order: i, note: null });
  });
});

const seed = { generated_from: 'data/family.source.json', people, person_details: details, parent_child: parentChild, unions };
writeFileSync(join(root, 'site/data/seed.json'), JSON.stringify(seed, null, 1) + '\n');

const lit = (v) => (v === null || v === undefined ? 'null' : typeof v === 'boolean' || typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, rows) => {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict do nothing;\n\n`;
};

const sql = `-- Generated by scripts/build-seed.mjs from data/family.source.json. Do not edit by hand.
-- Run once, after schema.sql, in the Supabase SQL editor.
begin;
${insert('people', people)}${insert('person_details', details)}${insert('parent_child', parentChild)}${insert('unions', unions)}commit;
`;
writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log(`people ${people.length}, parent links ${parentChild.length}, marriages ${unions.length}`);

// One file that does everything for a new Supabase project: schema, seed data
// and the first admin. The person setting up only changes the email on line 6.
const schema = readFileSync(join(root, 'supabase/schema.sql'), 'utf8');
const setup = `-- Jaggi Family Tree: complete first-time setup for a new Supabase project.
-- Generated by scripts/build-seed.mjs. Paste all of it into the Supabase SQL Editor and click Run.
--
-- >>> Change the email address on the next line to your own, keep the quotes: <<<
create temp table setup_admin as
select lower(trim('YOUR-EMAIL@example.com')) as email;

do $$ begin
  if (select email from setup_admin) like '%example.com' then
    raise exception 'Please change YOUR-EMAIL@example.com near the top of this script to your own email, then click Run again.';
  end if;
end $$;

${schema}
-- ---------------------------------------------------------------- family data from the PDFs
${insert('people', people)}${insert('person_details', details)}${insert('parent_child', parentChild)}${insert('unions', unions)}
-- ---------------------------------------------------------------- first admin
insert into public.invites (email, role, person_id)
select email, 'admin', '${uuid('sunil-kumar')}'::uuid from setup_admin
on conflict (email) do update set role = 'admin';

select 'Setup finished: ' || (select count(*) from public.people) || ' people loaded, admin invite for ' || (select email from setup_admin) as result;
`;
writeFileSync(join(root, 'supabase/setup.sql'), setup);
